/**
 * LooksFacts product catalogue — MVP local dataset.
 *
 * IMPORTANT — data provenance
 * ---------------------------
 * - Products are real, widely available items (mostly in Australia).
 * - Prices are INDICATIVE Australian RRPs in AUD, compiled manually. They
 *   are not live, vary by retailer and change over time.
 * - `keyIngredients` lists the headline ingredients the brand promotes. It
 *   is NOT a full ingredient (INCI) list and has not been independently
 *   verified by LooksFacts.
 * - `info` describes confidence in the entry:
 *     'brand'  – key ingredients reflect the brand's own marketing claims
 *     'sample' – details are incomplete or uncertain; shown as sample data
 * - `skinTypes` is only filled where the brand positions the product for
 *   specific skin types. An empty array means "not specified".
 * - `price` may later hold regional prices, e.g. { AUD: 19.99, GBP: 12.5 }.
 *   Currencies without an explicit price are converted from AUD and shown
 *   as estimates (see utils/currency.js).
 */

/**
 * Product photos: drop a file named <product-id>.(webp|jpg|jpeg|png|avif)
 * into src/assets/products/ and it is picked up automatically. Only add
 * images you have the rights to use (e.g. brand press kits or retailer
 * affiliate feeds). Products without a photo fall back to an illustration.
 */
const PHOTOS = Object.fromEntries(
  Object.entries(import.meta.glob('../assets/products/*.{webp,jpg,jpeg,png,avif}', { eager: true, import: 'default' })).map(
    ([path, url]) => [path.split('/').pop().replace(/\.[^.]+$/, ''), url],
  ),
)

function slugify(s) {
  return s
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/&/g, 'and')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '')
}

function p(category, brand, name, size, aud, keyIngredients, skinTypes, description, info = 'brand') {
  const id = slugify(`${brand} ${name}`)
  return {
    id,
    category,
    brand,
    name,
    size,
    price: { AUD: aud },
    keyIngredients,
    skinTypes,
    description,
    info,
    image: PHOTOS[id] ?? null, // see PHOTOS above
    retailerUrl: null, // verified retailer links to be added later
  }
}

